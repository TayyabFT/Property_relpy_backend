/**
 * Bundle the Express API for Vercel so .ts / .tsx email modules work
 * without a runtime tsx loader (which often crashes on serverless).
 */
import * as esbuild from "esbuild";
import { mkdirSync, writeFileSync } from "node:fs";

mkdirSync("api", { recursive: true });

await esbuild.build({
  entryPoints: ["src/vercel-handler.js"],
  bundle: true,
  platform: "node",
  target: "node20",
  format: "esm",
  outfile: "api/index.js",
  loader: {
    ".js": "js",
    ".ts": "ts",
    ".tsx": "tsx",
    ".json": "json",
  },
  jsx: "automatic",
  // Keep npm packages external — Vercel provides node_modules at runtime.
  // Our local .js/.ts/.tsx source is inlined into api/index.js.
  packages: "external",
  banner: {
    js: "// Generated by scripts/build-vercel.mjs — do not edit by hand\n",
  },
  logLevel: "info",
});

// Ensure this folder is treated as ESM (matches root package.json)
writeFileSync(
  "api/package.json",
  JSON.stringify({ type: "module" }, null, 2) + "\n",
);

console.log("Vercel API bundle written to api/index.js");
